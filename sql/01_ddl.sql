-- ---------------------------- PART A: CREATE -------------------------

CREATE TABLE party (
    party_id        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    party_name      VARCHAR2(100) NOT NULL,
    party_type      VARCHAR2(15)  NOT NULL,
    license_no      VARCHAR2(30)  NOT NULL,
    license_status  VARCHAR2(10)  DEFAULT 'ACTIVE' NOT NULL,
    license_expiry  DATE          NOT NULL,
    city            VARCHAR2(50),
    state           VARCHAR2(50),
    email           VARCHAR2(100),
    phone           VARCHAR2(15),
    CONSTRAINT pk_party PRIMARY KEY (party_id)
);

CREATE TABLE drug (
    drug_id               NUMBER GENERATED BY DEFAULT AS IDENTITY,
    drug_name             VARCHAR2(100) NOT NULL,
    generic_name          VARCHAR2(100),
    dosage_form           VARCHAR2(20),
    strength              VARCHAR2(20),
    requires_prescription CHAR(1) DEFAULT 'N' NOT NULL,
    min_storage_temp      NUMBER(4,1),
    max_storage_temp      NUMBER(4,1),
    CONSTRAINT pk_drug PRIMARY KEY (drug_id)
);

CREATE TABLE patient (
    patient_id    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    patient_name  VARCHAR2(100) NOT NULL,
    dob           DATE,
    gender        CHAR(1),
    phone         VARCHAR2(15),
    CONSTRAINT pk_patient PRIMARY KEY (patient_id)
);

CREATE TABLE batch (
    batch_id           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    batch_no           VARCHAR2(30) NOT NULL,
    drug_id            NUMBER       NOT NULL,
    manufacturer_id    NUMBER       NOT NULL,
    mfg_date           DATE         NOT NULL,
    expiry_date        DATE         NOT NULL,
    quantity_produced  NUMBER       NOT NULL,
    batch_status       VARCHAR2(12) DEFAULT 'ACTIVE' NOT NULL,
    CONSTRAINT pk_batch PRIMARY KEY (batch_id)
);

CREATE TABLE drug_unit (
    unit_id      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    serial_no    VARCHAR2(40) NOT NULL,
    batch_id     NUMBER       NOT NULL,
    unit_status  VARCHAR2(12) DEFAULT 'IN_STOCK' NOT NULL,
    CONSTRAINT pk_drug_unit PRIMARY KEY (unit_id)
);

CREATE TABLE shipment (
    shipment_id      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    from_party_id    NUMBER       NOT NULL,
    to_party_id      NUMBER       NOT NULL,
    dispatch_date    TIMESTAMP    NOT NULL,
    receive_date     TIMESTAMP,
    vehicle_no       VARCHAR2(20),
    shipment_status  VARCHAR2(12) DEFAULT 'IN_TRANSIT' NOT NULL,
    CONSTRAINT pk_shipment PRIMARY KEY (shipment_id)
);

CREATE TABLE custody_transfer (
    transfer_id    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    batch_id       NUMBER    NOT NULL,
    shipment_id    NUMBER    NOT NULL,
    seq_no         NUMBER    NOT NULL,
    quantity       NUMBER    NOT NULL,
    previous_hash  CHAR(64)  NOT NULL,
    current_hash   CHAR(64)  NOT NULL,
    recorded_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_custody_transfer PRIMARY KEY (transfer_id)
);

CREATE TABLE storage_log (
    log_id         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    batch_id       NUMBER       NOT NULL,
    party_id       NUMBER       NOT NULL,
    shipment_id    NUMBER,
    recorded_at    TIMESTAMP    NOT NULL,
    temperature_c  NUMBER(4,1)  NOT NULL,
    humidity_pct   NUMBER(4,1),
    CONSTRAINT pk_storage_log PRIMARY KEY (log_id)
);

CREATE TABLE dispensing_record (
    dispense_id       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    unit_id           NUMBER       NOT NULL,
    pharmacy_id       NUMBER       NOT NULL,
    patient_id        NUMBER       NOT NULL,
    dispense_date     DATE         DEFAULT SYSDATE NOT NULL,
    prescription_ref  VARCHAR2(30),
    CONSTRAINT pk_dispensing_record PRIMARY KEY (dispense_id)
);

CREATE TABLE alert (
    alert_id      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    alert_type    VARCHAR2(25)  NOT NULL,
    batch_id      NUMBER,
    unit_id       NUMBER,
    description   VARCHAR2(300),
    raised_at     TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    alert_status  VARCHAR2(10)  DEFAULT 'OPEN' NOT NULL,
    CONSTRAINT pk_alert PRIMARY KEY (alert_id)
);

CREATE TABLE user_account (
    user_id    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    username   VARCHAR2(30) NOT NULL,
    role_name  VARCHAR2(15) NOT NULL,
    party_id   NUMBER,
    is_active  CHAR(1) DEFAULT 'Y' NOT NULL,
    CONSTRAINT pk_user_account PRIMARY KEY (user_id)
);

CREATE TABLE audit_log (
    audit_id    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    table_name  VARCHAR2(30)  NOT NULL,
    operation   VARCHAR2(6)   NOT NULL,
    record_key  VARCHAR2(50),
    old_value   VARCHAR2(500),
    new_value   VARCHAR2(500),
    changed_by  VARCHAR2(30)  DEFAULT USER NOT NULL,
    changed_at  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_audit_log PRIMARY KEY (audit_id)
);

